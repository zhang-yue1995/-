CREATE INDEX idxcsi_statement_id ON cash_flow_statement_item(statement_id);

-- 13. 字段映射规则表
CREATE TABLE IF NOT EXISTS field_mapping_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_field_name VARCHAR(200) NOT NULL,
    target_field_name VARCHAR(100) NOT NULL,
    source_table VARCHAR(50),
    target_table VARCHAR(50),
    field_alias VARCHAR(200),
    unit VARCHAR(20),
    data_type VARCHAR(30),
    conversion_formula VARCHAR(500),
    priority INTEGER DEFAULT 0,
    is_active BOOLEAN DEFAULT TRUE,
    description VARCHAR(500),
    created_by BIGINT,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX idx_fmr_source ON field_mapping_rule(source_field_name);
CREATE INDEX idx_fmr_target ON field_mapping_rule(target_field_name);

-- 14. 财务指标定义表
CREATE TABLE IF NOT EXISTS financial_indicator (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    indicator_code VARCHAR(50) NOT NULL UNIQUE,
    indicator_name VARCHAR(100) NOT NULL,
    category VARCHAR(30) NOT NULL, -- SOLVENCY, PROFITABILITY, OPERATION, CASH_FLOW, GROWTH
    unit VARCHAR(20),
    formula TEXT,
    description TEXT,
    normal_range_min DECIMAL(10,4),
    normal_range_max DECIMAL(10,4),
    warning_threshold_low DECIMAL(10,4),
    warning_threshold_high DECIMAL(10,4),
    calculation_order INTEGER,
    status VARCHAR(20) DEFAULT 'ACTIVE',
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX idx_fi_category ON financial_indicator(category);
CREATE INDEX idx_fi_code ON financial_indicator(indicator_code);

-- 15. 财务指标值表
CREATE TABLE IF NOT EXISTS financial_indicator_value (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT,
    enterprise_id BIGINT NOT NULL,
    indicator_code VARCHAR(50) NOT NULL,
    indicator_name VARCHAR(100),
    category VARCHAR(30),
    "value" DECIMAL(18,4),
    unit VARCHAR(20),
    status VARCHAR(20),
    threshold_min DOUBLE,
    threshold_max DOUBLE,
    calculation_detail VARCHAR(1000),
    calculated_time TIMESTAMP,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fiv_report FOREIGN KEY (report_id) REFERENCES financial_report_archive(id),
    CONSTRAINT fiv_enterprise FOREIGN KEY (enterprise_id) REFERENCES enterprise(id)
);

CREATE INDEX idx_indicator_report ON financial_indicator_value(report_id, indicator_code);

-- 16. 财务健康评分表
CREATE TABLE IF NOT EXISTS financial_health_score (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT,
    enterprise_id BIGINT NOT NULL,
    report_date DATE,
    total_score DECIMAL(5,2),
    solvency_score DECIMAL(5,2),
    profitability_score DECIMAL(5,2),
    cash_flow_score DECIMAL(5,2),
    operation_score DECIMAL(5,2),
    growth_score DECIMAL(5,2),
    risk_level VARCHAR(20),
    solvency_weight DECIMAL(3,2),
    profitability_weight DECIMAL(3,2),
    cash_flow_weight DECIMAL(3,2),
    operation_weight DECIMAL(3,2),
    growth_weight DECIMAL(3,2),
    summary VARCHAR(2000),
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fhs_report FOREIGN KEY (report_id) REFERENCES financial_report_archive(id),
    CONSTRAINT fhs_enterprise FOREIGN KEY (enterprise_id) REFERENCES enterprise(id)
);

CREATE INDEX idx_health_score_enterprise ON financial_health_score(enterprise_id, report_date);

