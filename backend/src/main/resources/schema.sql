    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    statement_id BIGINT NOT NULL,
    item_name VARCHAR(100) NOT NULL,
    item_code VARCHAR(50),
    item_type VARCHAR(30), -- OPERATING, INVESTING, FINANCING
