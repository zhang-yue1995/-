-- 1. 用户表（使用sys_user避免H2保留关键字冲突）
CREATE TABLE IF NOT EXISTS sys_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    real_name VARCHAR(100),
    email VARCHAR(100),
    phone VARCHAR(20),
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    status INTEGER NOT NULL DEFAULT 1,
    last_login_time TIMESTAMP,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX idx_sys_user_username ON sys_user(username);
CREATE INDEX idx_sys_user_status ON sys_user(status);

-- 2. 企业表
CREATE TABLE IF NOT EXISTS enterprise (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enterprise_name VARCHAR(200) NOT NULL,
    enterprise_code VARCHAR(50) UNIQUE,
    industry VARCHAR(100),
    legal_person VARCHAR(100),
    registered_capital DECIMAL(18,2),
    establish_date DATE,
    address VARCHAR(500),
    contact_person VARCHAR(100),
    contact_phone VARCHAR(20),
    risk_level VARCHAR(20) DEFAULT 'NORMAL',
    health_score INTEGER,
    last_report_date DATE,
    manager_name VARCHAR(100),
    created_by BIGINT,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_enterprise_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id)
);

CREATE INDEX idx_enterprise_name ON enterprise(enterprise_name);
CREATE INDEX idx_enterprise_code ON enterprise(enterprise_code);
CREATE INDEX idx_enterprise_risk_level ON enterprise(risk_level);

-- 3. 财务报表归档表
CREATE TABLE IF NOT EXISTS financial_report_archive (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    enterprise_id BIGINT NOT NULL,
    report_type VARCHAR(30) NOT NULL,
    report_period VARCHAR(20) NOT NULL,
    report_year INTEGER NOT NULL,
    report_quarter INTEGER,
    report_month INTEGER,
    filing_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    validation_status VARCHAR(20),
    total_assets DECIMAL(18,2),
    total_liabilities DECIMAL(18,2),
    total_equity DECIMAL(18,2),
    revenue DECIMAL(18,2),
    net_profit DECIMAL(18,2),
    operating_cash_flow DECIMAL(18,2),
    data_source VARCHAR(50),
    data_quality_score DECIMAL(5,2),
    remarks TEXT,
    manager_name VARCHAR(100),
    uploaded_by BIGINT,
    reviewed_by BIGINT,
    reviewed_time TIMESTAMP,
    review_comment TEXT,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_archive_enterprise FOREIGN KEY (enterprise_id) REFERENCES enterprise(id),
    CONSTRAINT fk_archive_uploaded_by FOREIGN KEY (uploaded_by) REFERENCES sys_user(id),
    CONSTRAINT fk_archive_reviewed_by FOREIGN KEY (reviewed_by) REFERENCES sys_user(id)
);

CREATE INDEX idx_archive_enterprise_id ON financial_report_archive(enterprise_id);
CREATE INDEX idx_archive_status ON financial_report_archive(filing_status);
CREATE INDEX idx_archive_date ON financial_report_archive(report_year, report_quarter, report_month);

-- 4. 上传文件表
CREATE TABLE IF NOT EXISTS uploaded_file (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archive_id BIGINT,
    original_filename VARCHAR(255) NOT NULL,
    stored_filename VARCHAR(255),
    file_path VARCHAR(500) NOT NULL,
    file_size BIGINT NOT NULL,
    file_type VARCHAR(50) NOT NULL,
    mime_type VARCHAR(100),
    md5_hash VARCHAR(32),
    upload_status VARCHAR(20) NOT NULL DEFAULT 'UPLOADED',
    ocr_task_id BIGINT,
    uploaded_by BIGINT NOT NULL,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_file_archive FOREIGN KEY (archive_id) REFERENCES financial_report_archive(id),
    CONSTRAINT fk_file_uploaded_by FOREIGN KEY (uploaded_by) REFERENCES sys_user(id)
);

CREATE INDEX idx_file_archive_id ON uploaded_file(archive_id);
CREATE INDEX idx_file_upload_time ON uploaded_file(created_time);

-- 5. OCR任务表
CREATE TABLE IF NOT EXISTS ocr_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id BIGINT NOT NULL,
    task_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    task_type VARCHAR(30) NOT NULL,
    provider VARCHAR(30) DEFAULT 'http',
    total_fields INTEGER DEFAULT 0,
    recognized_fields INTEGER DEFAULT 0,
    high_confidence_count INTEGER DEFAULT 0,
    medium_confidence_count INTEGER DEFAULT 0,
    low_confidence_count INTEGER DEFAULT 0,
    average_confidence DECIMAL(7,4),
    processing_time_ms INTEGER,
    error_message TEXT,
    result_summary TEXT,
    source_enterprise_name VARCHAR(200),
    source_report_period VARCHAR(20),
    source_report_date DATE,
    source_unit VARCHAR(20),
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    created_by BIGINT NOT NULL,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_ocr_task_file FOREIGN KEY (file_id) REFERENCES uploaded_file(id),
    CONSTRAINT fk_ocr_task_created_by FOREIGN KEY (created_by) REFERENCES sys_user(id)
);

CREATE INDEX idx_ocr_task_file_id ON ocr_task(file_id);
CREATE INDEX idx_ocr_task_status ON ocr_task(task_status);

-- 6. OCR识别字段结果表
CREATE TABLE IF NOT EXISTS ocr_field_result (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocr_task_id BIGINT NOT NULL,
    field_name VARCHAR(100) NOT NULL,
    field_code VARCHAR(50),
    field_value VARCHAR(500),
    secondary_value VARCHAR(500),
    tertiary_value VARCHAR(500),
    numeric_value DECIMAL(18,2),
    confidence_score DECIMAL(7,4) NOT NULL,
    confidence_level VARCHAR(20),
    field_type VARCHAR(30),
    is_reviewed INTEGER DEFAULT 0,
    reviewed_value DECIMAL(18,2),
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP,
    review_comment VARCHAR(500),
    bounding_box VARCHAR(200),
    page_number INTEGER DEFAULT 1,
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_ocr_result_task FOREIGN KEY (ocr_task_id) REFERENCES ocr_task(id)
);

CREATE INDEX idx_ocr_result_task_id ON ocr_field_result(ocr_task_id);
CREATE INDEX idx_ocr_result_confidence ON ocr_field_result(confidence_score);
CREATE INDEX idx_ocr_result_reviewed ON ocr_field_result(is_reviewed);

-- 7. 资产负债表主表
CREATE TABLE IF NOT EXISTS balance_sheet (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    archive_id BIGINT NOT NULL,
    enterprise_id BIGINT NOT NULL,
    report_period VARCHAR(20) NOT NULL,
    report_date DATE NOT NULL,
    total_current_assets DECIMAL(18,2),
    total_non_current_assets DECIMAL(18,2),
    total_assets DECIMAL(18,2),
    total_current_liabilities DECIMAL(18,2),
    total_non_current_liabilities DECIMAL(18,2),
    total_liabilities DECIMAL(18,2),
    total_equity DECIMAL(18,2),
    balance_check_result VARCHAR(20),
    balance_difference DECIMAL(18,6),
    created_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_bs_archive FOREIGN KEY (archive_id) REFERENCES financial_report_archive(id),
    CONSTRAINT fk_bs_enterprise FOREIGN KEY (enterprise_id) REFERENCES enterprise(id)
);

CREATE INDEX idx_bs_archive_id ON balance_sheet(archive_id);
CREATE INDEX idx_bs_date ON balance_sheet(report_date);

